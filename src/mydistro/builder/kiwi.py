from __future__ import annotations

from pathlib import Path

import yaml


class BuilderError(RuntimeError):
    pass


def generate_kiwi_overlay(profile: Path, destination: Path) -> Path:
    """Generate the profile overlay portion for a future KIWI image build.

    v0.1 intentionally does not claim to build a universally bootable ISO yet.
    It stages the profile in a deterministic location that a distro-specific
    KIWI description can consume in the next milestone.
    """
    profile = profile.resolve()
    manifest = yaml.safe_load((profile / "manifest.yaml").read_text(encoding="utf-8"))
    destination.mkdir(parents=True, exist_ok=True)
    overlay = destination / "root/usr/share/mydistro/profile"
    overlay.mkdir(parents=True, exist_ok=True)

    (overlay / "manifest.yaml").write_text(
        yaml.safe_dump(manifest, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    marker = destination / "README-BUILDER.txt"
    marker.write_text(
        "This directory is a staged KIWI overlay generated by mydistro v0.1.\n"
        "The next milestone adds distro-specific ISO descriptions and Calamares integration.\n",
        encoding="utf-8",
    )
    return destination
